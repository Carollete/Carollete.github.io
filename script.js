(function flipbookReader() {
  const flipbook = document.getElementById("flipbook");
  if (!flipbook) return;

  const sectionTitle = document.getElementById("section-title");
  const pageArea = document.getElementById("page-area");
  const pageIndicator = document.getElementById("page-indicator");
  const prevBtn = document.getElementById("prev-page");
  const nextBtn = document.getElementById("next-page");
  const zoomInBtn = document.getElementById("zoom-in");
  const zoomOutBtn = document.getElementById("zoom-out");

  const id = new URLSearchParams(window.location.search).get("id");
  const section = secciones[id] || secciones.umbral;

  let currentPage = 0;
  let zoomLevel = 1;
  let pdfDoc = null;
  let pdfLoadingPromise = null;
  let pdfRenderTask = null;
  let isAnimatingFlip = false;
  let audioCtx = null;

  if (sectionTitle) sectionTitle.textContent = section.titulo;

  function pageHtmlByTipo(page, tipo) {
    if (page.pullquote) {
      return `
        <div class="pullquote-block">
          <div>
            <div class="quote-rule"></div>
            <p class="pullquote-text">${page.pullquote}</p>
            <div class="quote-rule"></div>
          </div>
        </div>
      `;
    }

    if (tipo === "galeria") {
      const headingHtml = page.heading ? `<h3>${page.heading}</h3>` : "";
      const bodyHtml = page.body ? `<p>${page.body}</p>` : "";
      return `
        ${headingHtml}
        ${bodyHtml}
        <div class="gallery-placeholder" aria-hidden="true">
          <img src="assets/pru.png" alt="Descripción de la imagen">
        </div>
        <p class="gallery-caption">Fragmento visual del archivo simbólico</p>
      `;
    }

    if (tipo === "reflexion") {
      if (page.heading && page.body) {
        return `
          <h3>${page.heading}</h3>
          <p>${page.body}</p>
        `;
      }

      return `
        <div class="pullquote-block">
          <div>
            <div class="quote-rule"></div>
            <p class="pullquote-text">Permanece con la respiración y escucha lo que emerge en el silencio.</p>
            <div class="quote-rule"></div>
          </div>
        </div>
      `;
    }

    const headingHtml = page.heading ? `<h3>${page.heading}</h3>` : "";
    const bodyHtml = page.body ? `<p>${page.body}</p>` : "";
    return `
      ${headingHtml}
      ${bodyHtml}
    `;
  }

  function updateIndicator() {
    if (!pageIndicator) return;
    const totalPages = section.tipo === "pdf" ? section.paginasTotales || 1 : section.paginas.length;
    pageIndicator.textContent = `Página ${currentPage + 1} de ${totalPages}`;
  }

  function ensurePdfJs() {
    if (window.pdfjsLib) return Promise.resolve(window.pdfjsLib);
    if (pdfLoadingPromise) return pdfLoadingPromise;

    pdfLoadingPromise = new Promise((resolve, reject) => {
      const script = document.createElement("script");
      script.src =
        "https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.min.js";
      script.onload = () => {
        if (!window.pdfjsLib) {
          reject(new Error("PDF.js no inicializado"));
          return;
        }
        resolve(window.pdfjsLib);
      };
      script.onerror = () => reject(new Error("No se pudo cargar PDF.js"));
      document.head.appendChild(script);
    });

    return pdfLoadingPromise;
  }

  async function ensurePdfDoc() {
    if (pdfDoc) return pdfDoc;

    const pdfjsLib = await ensurePdfJs();
    pdfjsLib.GlobalWorkerOptions.workerSrc =
      "https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js";

    const loadingTask = pdfjsLib.getDocument({
      url: section.pdfUrl,
      disableStream: true,
      disableAutoFetch: true
    });

    pdfDoc = await loadingTask.promise;
    section.paginasTotales = pdfDoc.numPages || 1;
    return pdfDoc;
  }

  function renderPdfShell() {
    if (!pageArea) return null;
    const watermarkText = section.marcaAgua || "REVISTA ORACULO · USO PERSONAL";
    const watermarkClass = section.watermarkEnabled ? "" : " is-hidden";

    pageArea.innerHTML = `
      <div class="pdf-book">
        <div class="pdf-page-wrap">
          <canvas class="pdf-canvas" id="pdf-canvas"></canvas>
          <div class="pdf-watermark${watermarkClass}" aria-hidden="true">
            <span>${watermarkText}</span>
            <span>${watermarkText}</span>
            <span>${watermarkText}</span>
            <span>${watermarkText}</span>
          </div>
          <div class="page-flip-sheet" aria-hidden="true"></div>
          <div class="page-corner-fold" aria-hidden="true"></div>
          <button class="page-hitbox page-hitbox-left" id="page-hitbox-left" aria-label="Página anterior"></button>
          <button class="page-hitbox page-hitbox-right" id="page-hitbox-right" aria-label="Página siguiente"></button>
        </div>
      </div>
    `;

    const leftHitbox = pageArea.querySelector("#page-hitbox-left");
    const rightHitbox = pageArea.querySelector("#page-hitbox-right");
    if (leftHitbox) leftHitbox.addEventListener("click", prevPage);
    if (rightHitbox) rightHitbox.addEventListener("click", nextPage);

    return pageArea.querySelector("#pdf-canvas");
  }

  function playPageFlipSound() {
    try {
      audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
      const now = audioCtx.currentTime;
      const noiseDuration = 0.12;
      const bufferSize = Math.floor(audioCtx.sampleRate * noiseDuration);
      const buffer = audioCtx.createBuffer(1, bufferSize, audioCtx.sampleRate);
      const data = buffer.getChannelData(0);
      for (let i = 0; i < bufferSize; i += 1) {
        data[i] = (Math.random() * 2 - 1) * (1 - i / bufferSize);
      }

      const noise = audioCtx.createBufferSource();
      noise.buffer = buffer;
      const noiseFilter = audioCtx.createBiquadFilter();
      noiseFilter.type = "bandpass";
      noiseFilter.frequency.value = 1200;
      const gain = audioCtx.createGain();
      gain.gain.setValueAtTime(0.0001, now);
      gain.gain.exponentialRampToValueAtTime(0.035, now + 0.02);
      gain.gain.exponentialRampToValueAtTime(0.0001, now + noiseDuration);
      noise.connect(noiseFilter);
      noiseFilter.connect(gain);
      gain.connect(audioCtx.destination);
      noise.start(now);
      noise.stop(now + noiseDuration);
    } catch (error) {
      // Si el navegador bloquea audio automático, simplemente no suena.
    }
  }

  async function renderPdfPage(direction = "next", withAnimation = true) {
    if (!pageArea || !section.pdfUrl) return;

    const totalPages = section.paginasTotales || 1;
    const pageNumber = Math.min(totalPages, Math.max(1, currentPage + 1));
    currentPage = pageNumber - 1;

    if (withAnimation && isAnimatingFlip) return;
    if (!withAnimation && isAnimatingFlip) {
      pageArea.classList.remove("flip-rtl", "flip-ltr");
      isAnimatingFlip = false;
    }

    if (withAnimation) {
      isAnimatingFlip = true;
      pageArea.classList.remove("flip-rtl", "flip-ltr");
      // Pase invertido: avanzar y retroceder intercambian sentido visual.
      pageArea.classList.add(direction === "next" ? "flip-ltr" : "flip-rtl");
      playPageFlipSound();
    }

    try {
      const doc = await ensurePdfDoc();
      const canvas = renderPdfShell();
      if (!canvas) return;

      const context = canvas.getContext("2d");
      if (!context) return;

      if (pdfRenderTask) {
        pdfRenderTask.cancel();
        pdfRenderTask = null;
      }

      const page = await doc.getPage(pageNumber);
      const baseViewport = page.getViewport({ scale: 1 });
      const maxWidth = Math.min(pageArea.clientWidth - 28, 760);
      const scaleByWidth = maxWidth / baseViewport.width;
      const finalScale = Math.max(0.6, scaleByWidth * zoomLevel);
      const viewport = page.getViewport({ scale: finalScale });

      canvas.width = Math.floor(viewport.width);
      canvas.height = Math.floor(viewport.height);

      pdfRenderTask = page.render({ canvasContext: context, viewport });
      await pdfRenderTask.promise;
      updateIndicator();
    } catch (error) {
      const isLocalFile = window.location.protocol === "file:";
      pageArea.innerHTML = `
        <p style="text-align:center; margin-bottom:10px;">
          No se pudo visualizar el PDF en modo revista.
        </p>
        <p style="text-align:center; font-size:0.92rem; opacity:0.82;">
          ${
            isLocalFile
              ? "Estás abriendo el sitio como archivo local (file://). Inicia un servidor local para permitir la lectura del PDF."
              : "Verifica que la ruta del PDF sea correcta y que el navegador permita cargarlo."
          }
        </p>
      `;
    } finally {
      if (withAnimation) {
        window.setTimeout(() => {
          pageArea.classList.remove("flip-rtl", "flip-ltr");
          isAnimatingFlip = false;
        }, 540);
      }
      pdfRenderTask = null;
    }
  }

  function renderPage() {
    if (section.tipo === "pdf") {
      renderPdfPage("next");
      return;
    }

    if (!pageArea) return;
    const page = section.paginas[currentPage];
    if (!page) return;

    pageArea.style.opacity = "0.15";
    window.setTimeout(() => {
      const content = pageHtmlByTipo(page, section.tipo);
      pageArea.innerHTML = `
        ${content}
        <div class="page-ornament">✦ ${currentPage + 1} ✦</div>
      `;
      pageArea.style.fontSize = `${14 * zoomLevel}px`;
      pageArea.style.opacity = "1";
      updateIndicator();
    }, 130);
  }

  function nextPage() {
    const maxPage =
      section.tipo === "pdf" ? section.paginasTotales - 1 : section.paginas.length - 1;
    if (currentPage < maxPage) {
      currentPage += 1;
      if (section.tipo === "pdf") {
        renderPdfPage("next");
      } else {
        renderPage();
      }
    }
  }

  function prevPage() {
    if (currentPage > 0) {
      currentPage -= 1;
      if (section.tipo === "pdf") {
        renderPdfPage("prev");
      } else {
        renderPage();
      }
    }
  }

  function zoomIn() {
    const maxZoom = section.tipo === "pdf" ? 3 : 1.65;
    const zoomStep = section.tipo === "pdf" ? 0.25 : 0.15;
    zoomLevel = Math.min(maxZoom, +(zoomLevel + zoomStep).toFixed(2));
    if (section.tipo === "pdf") {
      renderPdfPage("next", false);
      return;
    }
    renderPage();
  }

  function zoomOut() {
    const minZoom = section.tipo === "pdf" ? 0.55 : 0.75;
    const zoomStep = section.tipo === "pdf" ? 0.25 : 0.15;
    zoomLevel = Math.max(minZoom, +(zoomLevel - zoomStep).toFixed(2));
    if (section.tipo === "pdf") {
      renderPdfPage("next", false);
      return;
    }
    renderPage();
  }

  if (nextBtn) nextBtn.addEventListener("click", nextPage);
  if (prevBtn) prevBtn.addEventListener("click", prevPage);
  if (zoomInBtn) zoomInBtn.addEventListener("click", zoomIn);
  if (zoomOutBtn) zoomOutBtn.addEventListener("click", zoomOut);

  window.addEventListener("keydown", (event) => {
    if (section.tipo === "pdf") {
      const key = event.key.toLowerCase();
      const blocksSave = (event.ctrlKey || event.metaKey) && key === "s";
      const blocksPrint = (event.ctrlKey || event.metaKey) && key === "p";
      if (blocksSave || blocksPrint) {
        event.preventDefault();
        return;
      }
    }

    if (event.key === "ArrowRight") nextPage();
    if (event.key === "ArrowLeft") prevPage();
  });

  if (section.tipo === "pdf" && pageArea) {
    pageArea.addEventListener("contextmenu", (event) => event.preventDefault());
  }

  renderPage();
})();
