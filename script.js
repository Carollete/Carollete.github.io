(function orbitalCards() {
  const orbitRing = document.getElementById("orbit-ring");
  if (!orbitRing) return;
  const redealBtn = document.getElementById("redeal-cards");

  const cards = Array.from(orbitRing.querySelectorAll(".tarot-card"));
  if (!cards.length) return;
  const sectionIds = Object.keys(secciones);
  if (!sectionIds.length) return;

  const DECK_STORAGE_KEY = "oraculo_deck_v1";
  const REVEAL_STORAGE_KEY = "oraculo_deck_revealed_v1";

  let baseAngle = 0;
  const orbitRadius = 155;
  const centerX = 250;
  const centerY = 250;

  function positionCards() {
    baseAngle += 0.003;

    cards.forEach((card, index) => {
      const angle = baseAngle + (index * Math.PI * 2) / cards.length;
      const x = centerX + orbitRadius * Math.cos(angle) - 80;
      const y = centerY + orbitRadius * Math.sin(angle) - 130;

      card.style.left = `${x}px`;
      card.style.top = `${y}px`;
    });

    requestAnimationFrame(positionCards);
  }

  positionCards();

  function shuffleIds(ids) {
    const pool = [...ids];
    for (let i = pool.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return pool;
  }

  function randomizeSectionsForCards(cardList) {
    const pool = shuffleIds(sectionIds);
    const picks = [];
    for (let i = 0; i < cardList.length; i += 1) {
      picks.push(pool[i % pool.length]);
    }
    return picks;
  }

  function loadStoredDeck() {
    try {
      const raw = window.sessionStorage.getItem(DECK_STORAGE_KEY);
      if (!raw) return null;
      const parsed = JSON.parse(raw);
      if (!Array.isArray(parsed) || parsed.length !== cards.length) return null;
      const isValid = parsed.every((id) => typeof id === "string" && secciones[id]);
      return isValid ? parsed : null;
    } catch (error) {
      return null;
    }
  }

  function saveDeck(ids) {
    window.sessionStorage.setItem(DECK_STORAGE_KEY, JSON.stringify(ids));
  }

  function loadRevealedState() {
    try {
      const raw = window.sessionStorage.getItem(REVEAL_STORAGE_KEY);
      if (!raw) return null;
      const parsed = JSON.parse(raw);
      if (!Array.isArray(parsed) || parsed.length !== cards.length) return null;
      return parsed.map((item) => item === true);
    } catch (error) {
      return null;
    }
  }

  function saveRevealedState(revealed) {
    window.sessionStorage.setItem(REVEAL_STORAGE_KEY, JSON.stringify(revealed));
  }

  function navigateWithFlash(card, id, delay = 220) {
    if (!id) return;
    card.classList.add("flash");
    window.setTimeout(() => {
      window.location.href = `seccion.html?id=${encodeURIComponent(id)}`;
    }, delay);
  }

  function applyCardVisual(card, revealed, sectionId) {
    const section = secciones[sectionId];
    const labelEl = card.querySelector(".card-label");
    const nameEl = card.querySelector(".card-name");

    card.dataset.id = sectionId;
    card.dataset.revealed = revealed ? "true" : "false";
    card.classList.toggle("is-revealed", revealed);

    if (revealed) {
      if (labelEl) labelEl.textContent = "Sección revelada";
      if (nameEl) nameEl.textContent = section ? section.titulo : "Sección";
      card.setAttribute("aria-label", `Abrir ${section ? section.titulo : "sección"}`);
    } else {
      if (labelEl) labelEl.textContent = "Presencia";
      if (nameEl) nameEl.textContent = "Pulsa para revelar";
      card.setAttribute("aria-label", "Carta sellada");
    }
  }

  let assignedIds = loadStoredDeck() || randomizeSectionsForCards(cards);
  let revealedState = loadRevealedState() || cards.map(() => false);

  if (assignedIds.length !== cards.length) {
    assignedIds = randomizeSectionsForCards(cards);
  }
  if (revealedState.length !== cards.length) {
    revealedState = cards.map(() => false);
  }

  saveDeck(assignedIds);
  saveRevealedState(revealedState);

  function renderCards() {
    cards.forEach((card, index) => {
      applyCardVisual(card, revealedState[index], assignedIds[index]);
    });
  }

  function revealAllCards() {
    revealedState = cards.map(() => true);
    saveRevealedState(revealedState);
    renderCards();
  }

  cards.forEach((card, index) => {
    function revealOrNavigate() {
      const id = card.dataset.id;
      if (!id) return;

      if (!revealedState[index]) {
        // Primer clic: revela todas y entra de inmediato a la elegida.
        revealAllCards();
        navigateWithFlash(card, id);
        return;
      }

      navigateWithFlash(card, id);
    }

    card.addEventListener("click", revealOrNavigate);

    card.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        revealOrNavigate();
      }
    });
  });

  if (redealBtn) {
    redealBtn.addEventListener("click", () => {
      assignedIds = randomizeSectionsForCards(cards);
      revealedState = cards.map(() => false);
      saveDeck(assignedIds);
      saveRevealedState(revealedState);
      renderCards();
    });
  }

  renderCards();
})();

